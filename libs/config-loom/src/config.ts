/**
 * Files config-loom refuses to generate, whatever the config says. pnpm and
 * the tooling itself own these — generating them from a template would break
 * workspace resolution itself.
 */
export const FORBIDDEN_BASENAMES = new Set([
  'package.json',
  'pnpm-workspace.yaml',
  'pnpm-workspace.json5',
  'pnpm-lock.yaml',
  'package-lock.json',
  'yarn.lock',
  'turbo.json',
  'config-loom.json',
  'config-loom.jsonc',
  'config-loom.yaml',
  'config-loom.yml',
  '.gitignore',
  '.npmrc',
]);

export const DEFAULT_CONFIG_FILENAMES = ['config-loom.yaml', 'config-loom.yml'];

const DEFAULT_BANNER_TEXT =
  "Generated by config-loom — do not edit by hand. Change config-loom.yaml and run 'config-loom sync'.";

const FORMATS = new Set<FileFormat>(['json', 'jsonc', 'ts', 'text']);
const ARRAY_POLICIES = new Set<ArrayPolicy>(['replace', 'concat', 'unique']);

export function defaultFormatFor(file: string): FileFormat {
  const base = file.split('/').pop() ?? file;
  if (base.endsWith('.jsonc')) {
    return 'jsonc';
  }
  // tsconfig/jsconfig: tsc parses comments and VS Code treats exactly
  // these names as jsonc. They stay jsonc for INPUT tolerance, but the
  // banner defaults off (defaultBannerFor): real-world configs do
  // require('tsconfig.json'), and Node's JSON loader is strict.
  if (base === 'tsconfig.json' || base === 'jsconfig.json') {
    return 'jsonc';
  }
  // other .json files go through strict parsers (nest CLI, bundlers…)
  // and strict IDE modes — keep them comment-free.
  if (base.endsWith('.json')) {
    return 'json';
  }
  // TypeScript AND JavaScript config files (vitest.config.ts,
  // eslint.config.mjs, jest.config.cjs…) get the token-stream format:
  // spacing/comment/quote drift stops being a rule. The dialect follows
  // the extension (JSX only where the extension allows it).
  if (/\.[cm]?[jt]sx?$/i.test(base)) {
    return 'ts';
  }
  return 'text';
}

/** Whether a spec without an explicit `banner` gets one. */
export function defaultBannerFor(file: string): boolean {
  const base = file.split('/').pop() ?? file;
  // A file named *.jsonc opted into comments by name; tsconfig/jsconfig
  // did not, and tools routinely JSON.parse them (jest configs, webpack,
  // pnpm manifests…) — never banner them by default.
  return base === 'tsconfig.json' || base === 'jsconfig.json' ? false : true;
}

function resolveBanner(
  label: string,
  file: string,
  format: FileFormat,
  banner: string | boolean | undefined,
  errors: string[],
): string | false {
  if (banner === undefined || banner === true) {
    if (format === 'jsonc' && (banner === true || defaultBannerFor(file))) {
      return `/* ${DEFAULT_BANNER_TEXT} */`;
    }
    if (banner === true && format === 'ts') {
      return `// ${DEFAULT_BANNER_TEXT}`;
    }
    if (banner === true && format === 'text') {
      errors.push(
        `files["${label}"]: "banner": true is not supported for text files — provide the banner string explicitly (with its own comment syntax) or omit it`,
      );
    }
    return false;
  }
  if (banner === false) {
    return false;
  }
  if (typeof banner !== 'string') {
    errors.push(`files["${label}"]: "banner" must be a string, true or false`);
    return false;
  }
  if (format === 'json') {
    errors.push(
      `files["${label}"]: "banner" cannot be used with format "json" (comments are not valid JSON) — use format "jsonc" instead`,
    );
    return false;
  }
  return banner;
}

/**
 * Compile an `include`/`exclude` prop (a regex string or a list of them)
 * into anchored regexes. Empty/undefined yields an empty list.
 */
function compilePatternList(
  label: string,
  field: 'include' | 'exclude',
  raw: string | string[] | undefined,
  errors: string[],
): RegExp[] {
  if (raw === undefined) {
    return [];
  }
  const list = typeof raw === 'string' ? [raw] : raw;
  if (!Array.isArray(list)) {
    errors.push(
      `files["${label}"]: "${field}" must be a string or a list of strings`,
    );
    return [];
  }
  const out: RegExp[] = [];
  for (const key of list) {
    if (typeof key !== 'string' || key.length === 0) {
      errors.push(
        `files["${label}"]: ${field} pattern must be a non-empty string`,
      );
      continue;
    }
    try {
      out.push(new RegExp(`^(?:${key})$`));
    } catch (e) {
      errors.push(
        `files["${label}"]: ${field} "${key}" is not a valid regular expression: ${
          (e as Error).message
        }`,
      );
    }
  }
  return out;
}

/**
 * Normalize a written value against the format. `json`/`jsonc` accept a
 * plain object OR a string containing JSONC text (YAML block scalar) —
 * strings are parsed eagerly so a broken template fails at load, not at
 * render. `text` accepts strings only; `ts` accepts strings that must
 * parse as TypeScript (a broken rule value fails at load, not at sync).
 */
function parseValue(
  label: string,
  where: string,
  raw: unknown,
  format: FileFormat,
  file: string,
  errors: string[],
): JsonValue | string | undefined {
  if (isTextLike(format)) {
    if (typeof raw === 'string') {
      if (format === 'ts') {
        try {
          assertTypeScript(raw, file);
        } catch (e) {
          errors.push(`files["${label}"]: ${where}: ${(e as Error).message}`);
          return undefined;
        }
      }
      return raw;
    }
    errors.push(
      `files["${label}"]: ${where} must be a string for ${format} files`,
    );
    return undefined;
  }
  if (isPlainObject(raw)) {
    return raw;
  }
  if (typeof raw === 'string') {
    let parsed: JsonValue;
    try {
      parsed = parseJsonc(raw, `${where} text`);
    } catch (e) {
      errors.push(`files["${label}"]: ${(e as Error).message}`);
      return undefined;
    }
    if (!isPlainObject(parsed)) {
      errors.push(
        `files["${label}"]: ${where} text must contain a JSON object for ${format} files`,
      );
      return undefined;
    }
    return parsed;
  }
  errors.push(
    `files["${label}"]: ${where} must be an object (or a string of ${format} text)`,
  );
  return undefined;
}

/**
 * Compile the YAML rules list. Every entry is a regex rule — the base
 * content is the entry-level `default` property, so a pattern of `default`
 * legitimately matches a workspace folder named `default`. Rule values
 * must have content: scoping is the job of `include`/`exclude`.
 */
export function compileRules(
  label: string,
  format: FileFormat,
  file: string,
  rules: RuleInput[],
  errors: string[],
): CompiledRule[] {
  // Patterns are wrapped in a non-capturing group anchored at both ends at
  // match time, so an explicit ^...$ written by the user stays harmless.
  const compiled: CompiledRule[] = [];
  rules.forEach((entry, index) => {
    if (!isPlainObject(entry)) {
      errors.push(
        `files["${label}"]: rules[${index}] must be an object with a "pattern" prop`,
      );
      return;
    }
    const record = entry as Record<string, unknown>;
    const pattern = record.pattern;
    if (typeof pattern !== 'string' || pattern.length === 0) {
      errors.push(
        `files["${label}"]: rules[${index}] needs a non-empty string "pattern"`,
      );
      return;
    }
    const unknown = Object.keys(record).filter(
      (key) => key !== 'pattern' && key !== 'value',
    );
    if (unknown.length > 0) {
      errors.push(
        `files["${label}"]: rules[${index}] has unknown prop(s) ${unknown.join(', ')} — only "pattern", "value" and "template" are allowed`,
      );
      return;
    }
    if (
      !('value' in record) ||
      record.value === null ||
      record.value === undefined
    ) {
      errors.push(
        `files["${label}"]: rule "${pattern}" needs a "value" — values must have content (use "include"/"exclude" to scope workspaces out)`,
      );
      return;
    }
    const value = parseValue(
      label,
      `rule "${pattern}"`,
      record.value,
      format,
      file,
      errors,
    );
    if (value === undefined) {
      return;
    }
    try {
      compiled.push({ pattern, regex: new RegExp(`^(?:${pattern})$`), value });
    } catch (e) {
      errors.push(
        `files["${label}"]: rule "${pattern}" is not a valid regular expression: ${
          (e as Error).message
        }`,
      );
    }
  });
  return compiled;
}

/** Normalize a workspace-relative target path. */
function normalizeTarget(raw: string): string {
  return raw.replace(/\\/g, '/').replace(/^\.\//, '');
}

export function compileConfig(
  input: LoomConfigInput,
  label: string,
): LoomConfig {
  if (!isPlainObject(input)) {
    throw new LoomError(`${label}: expected a YAML mapping at the top level`);
  }
  const errors: string[] = [];
  if (!isPlainObject(input.files) || Object.keys(input.files).length === 0) {
    throw new LoomError(`${label}: "files" must be a non-empty mapping`);
  }

  const files: Record<string, CompiledFileEntry> = {};
  for (const [entryName, spec] of Object.entries(input.files)) {
    if (!isPlainObject(spec)) {
      errors.push(
        `files["${entryName}"]: expected an object with "default" and "rules"`,
      );
      continue;
    }
    const file = normalizeTarget(spec.filename ?? entryName);
    const labelName =
      spec.filename !== undefined ? `${entryName} → ${file}` : entryName;
    const basename = file.slice(file.lastIndexOf('/') + 1).toLowerCase();
    if (
      file.length === 0 ||
      path.isAbsolute(file) ||
      file.split('/').includes('..')
    ) {
      errors.push(
        `files["${labelName}"]: filename must be a relative path without ".." segments`,
      );
      continue;
    }
    if (FORBIDDEN_BASENAMES.has(basename)) {
      errors.push(
        `files["${labelName}"]: "${basename}" can never be generated by config-loom (owned by pnpm/git/tooling itself)`,
      );
      continue;
    }
    const format = spec.format ?? defaultFormatFor(file);
    if (!FORMATS.has(format)) {
      errors.push(
        `files["${labelName}"]: unknown format "${format}" (use json, jsonc, ts or text)`,
      );
      continue;
    }
    const arrays = spec.arrays ?? 'replace';
    if (!ARRAY_POLICIES.has(arrays)) {
      errors.push(
        `files["${labelName}"]: unknown arrays policy "${arrays}" (use replace, concat or unique)`,
      );
      continue;
    }
    if ('template' in spec) {
      errors.push(
        `files["${labelName}"]: "template" must be resolved before compiling — load the file with loadConfig (or call resolveTemplates first)`,
      );
      continue;
    }
    if (spec.rules !== undefined && !Array.isArray(spec.rules)) {
      errors.push(
        `files["${labelName}"]: "rules" must be a list of { pattern, value } entries`,
      );
      continue;
    }
    if (!('default' in spec)) {
      errors.push(
        `files["${labelName}"]: "default" is required (or a "template" file) — every generated file has base content; use "include" to restrict which workspaces get it`,
      );
      continue;
    }
    if (spec.default === null) {
      errors.push(
        `files["${labelName}"]: "default" must have a value — null is not supported; use "include"/"exclude" to restrict scope`,
      );
      continue;
    }
    const defaultValue = parseValue(
      labelName,
      '"default"',
      spec.default,
      format,
      file,
      errors,
    );
    if (defaultValue === undefined) {
      continue;
    }
    const banner = resolveBanner(labelName, file, format, spec.banner, errors);
    const include = compilePatternList(
      labelName,
      'include',
      spec.include,
      errors,
    );
    const exclude = compilePatternList(
      labelName,
      'exclude',
      spec.exclude,
      errors,
    );
    const rules = compileRules(
      labelName,
      format,
      file,
      spec.rules ?? [],
      errors,
    );

    const scope: CompiledScope = {
      include,
      exclude,
      format,
      arrays,
      banner,
      defaultValue,
      rules,
    };
    const entry = (files[file] ??= { file, scopes: [] });
    entry.scopes.push(scope);
  }

  if ('workspaces' in input) {
    errors.push(
      '"workspaces" is not supported: workspace directories come from pnpm itself (`pnpm -r exec pwd`)',
    );
  }

  if (errors.length > 0) {
    throw new LoomError(`${label}:\n  - ${errors.join('\n  - ')}`);
  }

  return {
    exclude: Array.isArray(input.exclude) ? input.exclude : [],
    files,
  };
}

/**
 * Repo-relative template file whose content becomes a value. `text` specs
 * take the bytes verbatim; `json`/`jsonc` specs parse the file (comments
 * allowed — templates are hand-written).
 */
async function readTemplate(
  root: string,
  label: string,
  template: string,
  format: FileFormat,
  errors: string[],
): Promise<JsonValue | string | undefined> {
  if (typeof template !== 'string' || template.length === 0) {
    errors.push(`${label}: "template" must be a non-empty repo-relative path`);
    return undefined;
  }
  const target = path.resolve(root, template);
  const rootDir = path.resolve(root);
  if (path.isAbsolute(template) || !target.startsWith(rootDir + path.sep)) {
    errors.push(
      `${label}: template "${template}" must stay inside the repository`,
    );
    return undefined;
  }
  let text: string;
  try {
    text = await readFile(target, 'utf8');
  } catch {
    errors.push(`${label}: template "${template}" not found`);
    return undefined;
  }
  if (isTextLike(format)) {
    return text;
  }
  try {
    return parseJsonc(text, `template "${template}"`);
  } catch (e) {
    errors.push(`${label}: ${(e as Error).message}`);
    return undefined;
  }
}

/**
 * Replace every `template` reference (entry-level for `default`, or per-rule
 * for `value`) with the file content, before compilation.
 */
export async function resolveTemplates(
  input: LoomConfigInput,
  root: string,
  sourceLabel = 'config',
): Promise<LoomConfigInput> {
  if (!isPlainObject(input) || !isPlainObject(input.files)) {
    return input; // compileConfig reports top-level shape errors
  }
  const errors: string[] = [];
  const files: Record<string, FileSpecInput> = {};
  for (const [name, spec] of Object.entries(input.files)) {
    if (!isPlainObject(spec)) {
      files[name] = spec;
      continue;
    }
    const label = `files["${name}"]`;
    const target =
      spec.filename !== undefined ? normalizeTarget(spec.filename) : name;
    const format = spec.format ?? defaultFormatFor(target);
    const next: Record<string, unknown> = { ...spec };
    if ('template' in next) {
      const template = next.template;
      delete next.template;
      if ('default' in next) {
        errors.push(
          `${label}: "template" and "default" are mutually exclusive`,
        );
      } else if (typeof template !== 'string') {
        errors.push(
          `${label}: "template" must be a repo-relative path string (null values are not supported)`,
        );
      } else {
        const value = await readTemplate(root, label, template, format, errors);
        if (value !== undefined) {
          next.default = value;
        }
      }
    }
    if (Array.isArray(next.rules)) {
      const resolved: unknown[] = [];
      for (const [index, rule] of (next.rules as RuleInput[]).entries()) {
        if (!isPlainObject(rule) || !('template' in rule)) {
          resolved.push(rule);
          continue;
        }
        const entry: Record<string, unknown> = { ...rule };
        const template = entry.template;
        delete entry.template;
        const ruleLabel = `${label} rules[${index}]`;
        if ('value' in entry) {
          errors.push(
            `${ruleLabel}: "template" and "value" are mutually exclusive`,
          );
        } else if (typeof template !== 'string') {
          errors.push(
            `${ruleLabel}: "template" must be a repo-relative path string (null values are not supported)`,
          );
        } else {
          const value = await readTemplate(
            root,
            ruleLabel,
            template,
            format,
            errors,
          );
          if (value !== undefined) {
            entry.value = value;
          }
        }
        resolved.push(entry);
      }
      next.rules = resolved;
    }
    files[name] = next;
  }
  if (errors.length > 0) {
    throw new LoomError(`${sourceLabel}:\n  - ${errors.join('\n  - ')}`);
  }
  return { ...input, files };
}

/** Every template path referenced by a raw config input, sorted. */
export function collectTemplatePaths(input: unknown): string[] {
  if (!isPlainObject(input) || !isPlainObject(input.files)) {
    return [];
  }
  const found = new Set<string>();
  for (const spec of Object.values(input.files)) {
    if (!isPlainObject(spec)) {
      continue;
    }
    const template = (spec as { template?: unknown }).template;
    if (typeof template === 'string' && template.length > 0) {
      found.add(template);
    }
    const rules = (spec as { rules?: unknown }).rules;
    if (Array.isArray(rules)) {
      for (const rule of rules) {
        if (!isPlainObject(rule)) {
          continue;
        }
        const ruleTemplate = (rule as { template?: unknown }).template;
        if (typeof ruleTemplate === 'string' && ruleTemplate.length > 0) {
          found.add(ruleTemplate);
        }
      }
    }
  }
  return [...found].sort();
}

/** Locate and load config-loom.yaml from the repo root. */
export async function loadConfig(
  root: string,
  explicitPath?: string,
): Promise<{ config: LoomConfig; path: string }> {
  const candidates = explicitPath
    ? [explicitPath]
    : DEFAULT_CONFIG_FILENAMES.map((name) => `${root}/${name}`);
  for (const candidate of candidates) {
    let text: string;
    try {
      text = await readFile(candidate, 'utf8');
    } catch {
      continue;
    }
    const parsed = parseYaml(text, { prettyErrors: true }) as unknown;
    const resolved = await resolveTemplates(
      parsed as LoomConfigInput,
      root,
      candidate,
    );
    const config = compileConfig(resolved, candidate);
    return { config, path: candidate };
  }
  throw new LoomError(
    `no loom configuration found (looked for: ${candidates.join(', ')}) — run 'config-loom init' first`,
  );
}
