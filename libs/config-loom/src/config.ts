import { parseJsonc } from './jsonc';
import { isPlainObject } from './util';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { parse as parseYaml } from 'yaml';
import type {
  ArrayPolicy,
  CompiledFileEntry,
  CompiledRule,
  FileFormat,
  JsonValue,
  LoomConfig,
  FileSpecInput,
  LoomConfigInput,
  RuleInput,
} from './types';

/**
 * Files config-loom refuses to generate, whatever the config says. pnpm and
 * the tooling itself own these — generating them from a template would break
 * workspace resolution itself.
 */
export const FORBIDDEN_BASENAMES = new Set([
  'package.json',
  'pnpm-workspace.yaml',
  'pnpm-workspace.json5',
  'pnpm-lock.yaml',
  'package-lock.json',
  'yarn.lock',
  'turbo.json',
  'config-loom.json',
  'config-loom.jsonc',
  'config-loom.yaml',
  'config-loom.yml',
  '.gitignore',
  '.npmrc',
]);

export const DEFAULT_CONFIG_FILENAMES = ['config-loom.yaml', 'config-loom.yml'];

const DEFAULT_BANNER_TEXT =
  "Generated by config-loom — do not edit by hand. Change config-loom.yaml and run 'config-loom sync'.";

const FORMATS = new Set<FileFormat>(['json', 'jsonc', 'text']);
const ARRAY_POLICIES = new Set<ArrayPolicy>(['replace', 'concat', 'unique']);

export function defaultFormatFor(file: string): FileFormat {
  const base = file.split('/').pop() ?? file;
  if (base.endsWith('.jsonc')) {
    return 'jsonc';
  }
  // tsconfig/jsconfig: tsc parses comments and VS Code treats exactly
  // these names as jsonc. They stay jsonc for INPUT tolerance, but the
  // banner defaults off (defaultBannerFor): real-world configs do
  // require('tsconfig.json'), and Node's JSON loader is strict.
  if (base === 'tsconfig.json' || base === 'jsconfig.json') {
    return 'jsonc';
  }
  // other .json files go through strict parsers (nest CLI, bundlers…)
  // and strict IDE modes — keep them comment-free.
  if (base.endsWith('.json')) {
    return 'json';
  }
  return 'text';
}

/** Whether a spec without an explicit `banner` gets one. */
export function defaultBannerFor(file: string): boolean {
  const base = file.split('/').pop() ?? file;
  // A file named *.jsonc opted into comments by name; tsconfig/jsconfig
  // did not, and tools routinely JSON.parse them (jest configs, webpack,
  // pnpm manifests…) — never banner them by default.
  return base === 'tsconfig.json' || base === 'jsconfig.json' ? false : true;
}

function resolveBanner(
  file: string,
  format: FileFormat,
  banner: string | boolean | undefined,
  errors: string[],
): string | false {
  if (banner === undefined || banner === true) {
    if (format === 'jsonc' && (banner === true || defaultBannerFor(file))) {
      return `/* ${DEFAULT_BANNER_TEXT} */`;
    }
    if (banner === true && format === 'text') {
      errors.push(
        `files["${file}"]: "banner": true is not supported for text files — provide the banner string explicitly (with its own comment syntax) or omit it`,
      );
    }
    return false;
  }
  if (banner === false) {
    return false;
  }
  if (typeof banner !== 'string') {
    errors.push(`files["${file}"]: "banner" must be a string, true or false`);
    return false;
  }
  if (format === 'json') {
    errors.push(
      `files["${file}"]: "banner" cannot be used with format "json" (comments are not valid JSON) — use format "jsonc" instead`,
    );
    return false;
  }
  return banner;
}

/**
 * Compile the YAML rules list. Every entry is a regex rule — the base
 * content is the spec-level `default` property, so a pattern of `default`
 * legitimately matches a workspace folder named `default`.
 */
export function compileRules(
  file: string,
  format: FileFormat,
  rules: RuleInput[],
  errors: string[],
): CompiledRule[] {
  // Patterns are wrapped in a non-capturing group anchored at both ends at
  // match time, so an explicit ^...$ written by the user stays harmless.
  const compiled: CompiledRule[] = [];
  rules.forEach((entry, index) => {
    if (!isPlainObject(entry)) {
      errors.push(
        `files["${file}"]: rules[${index}] must be an object with a "pattern" prop`,
      );
      return;
    }
    const record = entry as Record<string, JsonValue | string | null>;
    const pattern = record.pattern;
    if (typeof pattern !== 'string' || pattern.length === 0) {
      errors.push(
        `files["${file}"]: rules[${index}] needs a non-empty string "pattern"`,
      );
      return;
    }
    const unknown = Object.keys(record).filter(
      (key) => key !== 'pattern' && key !== 'value',
    );
    if (unknown.length > 0) {
      errors.push(
        `files["${file}"]: rules[${index}] has unknown prop(s) ${unknown.join(', ')} — only "pattern", "value" and "template" are allowed`,
      );
      return;
    }
    const value = record.value ?? null;
    if (
      value !== null &&
      (format === 'text' ? typeof value !== 'string' : !isPlainObject(value))
    ) {
      errors.push(
        `files["${file}"]: rule "${pattern}" must ${
          format === 'text'
            ? 'be a string for text files'
            : `be an object for ${format} files`
        }`,
      );
      return;
    }
    try {
      compiled.push({
        pattern,
        // Validate the user regex eagerly, wrapped anchored.
        regex: new RegExp(`^(?:${pattern})$`),
        value,
      });
    } catch (e) {
      errors.push(
        `files["${file}"]: rule "${pattern}" is not a valid regular expression: ${
          (e as Error).message
        }`,
      );
    }
  });
  return compiled;
}

export function compileConfig(
  input: LoomConfigInput,
  label: string,
): LoomConfig {
  if (!isPlainObject(input)) {
    throw new LoomError(`${label}: expected a JSON object at the top level`);
  }
  const errors: string[] = [];
  if (!isPlainObject(input.files) || Object.keys(input.files).length === 0) {
    throw new LoomError(`${label}: "files" must be a non-empty object`);
  }

  const files: Record<string, CompiledFileEntry> = {};
  for (const [rawName, spec] of Object.entries(input.files)) {
    const file = rawName.replace(/\\/g, '/').replace(/^\.\//, '');
    const basename = file.slice(file.lastIndexOf('/') + 1).toLowerCase();
    if (path.isAbsolute(file) || file.split('/').includes('..')) {
      errors.push(
        `files["${rawName}"]: must be a relative path without ".." segments`,
      );
      continue;
    }
    if (FORBIDDEN_BASENAMES.has(basename)) {
      errors.push(
        `files["${rawName}"]: "${basename}" can never be generated by config-loom (owned by pnpm/git/tooling itself)`,
      );
      continue;
    }
    if (!isPlainObject(spec)) {
      errors.push(`files["${rawName}"]: expected an object with "rules"`);
      continue;
    }
    const format = spec.format ?? defaultFormatFor(file);
    if (!FORMATS.has(format)) {
      errors.push(
        `files["${rawName}"]: unknown format "${format}" (use json, jsonc or text)`,
      );
      continue;
    }
    const arrays = spec.arrays ?? 'replace';
    if (!ARRAY_POLICIES.has(arrays)) {
      errors.push(
        `files["${rawName}"]: unknown arrays policy "${arrays}" (use replace, concat or unique)`,
      );
      continue;
    }
    if ('template' in spec) {
      errors.push(
        `files["${rawName}"]: "template" must be resolved before compiling — load the file with loadConfig (or call resolveTemplates first)`,
      );
      continue;
    }
    if (spec.rules !== undefined && !Array.isArray(spec.rules)) {
      errors.push(
        `files["${rawName}"]: "rules" must be a list of { pattern, value } entries`,
      );
      continue;
    }
    const hasDefaultProp = 'default' in spec;
    if (!hasDefaultProp && (spec.rules?.length ?? 0) === 0) {
      errors.push(
        `files["${rawName}"]: needs a "default" value and/or at least one rule`,
      );
      continue;
    }
    const banner = resolveBanner(file, format, spec.banner, errors);
    const rules = compileRules(file, format, spec.rules ?? [], errors);
    const hasDefault = hasDefaultProp;
    let defaultValue: JsonValue | string | null = null;
    if (hasDefaultProp) {
      const base = spec.default ?? null;
      if (
        base !== null &&
        (format === 'text' ? typeof base !== 'string' : !isPlainObject(base))
      ) {
        errors.push(
          `files["${file}"]: "default" must ${
            format === 'text'
              ? 'be a string for text files'
              : `be an object for ${format} files`
          }`,
        );
        continue;
      }
      defaultValue = base;
    }
    const exclude: RegExp[] = [];
    if (spec.exclude !== undefined) {
      if (!Array.isArray(spec.exclude)) {
        errors.push(`files["${file}"]: "exclude" must be an array of strings`);
      } else {
        for (const key of spec.exclude) {
          if (typeof key !== 'string') {
            errors.push(`files["${file}"]: exclude pattern must be a string`);
            continue;
          }
          try {
            new RegExp(key);
          } catch (e) {
            errors.push(
              `files["${file}"]: exclude "${key}" is not a valid regular expression: ${
                (e as Error).message
              }`,
            );
            continue;
          }
          exclude.push(new RegExp(`^(?:${key})$`));
        }
      }
    }
    files[file] = {
      file,
      format,
      arrays,
      banner,
      exclude,
      hasDefault,
      defaultValue,
      rules,
    };
  }

  if ('workspaces' in input) {
    errors.push(
      '"workspaces" is not supported: workspace directories come from pnpm itself (`pnpm -r exec pwd`)',
    );
  }

  if (errors.length > 0) {
    throw new LoomError(`${label}:\n  - ${errors.join('\n  - ')}`);
  }

  return {
    exclude: Array.isArray(input.exclude) ? input.exclude : [],
    files,
  };
}

/**
 * Repo-relative template file whose content becomes a value. `text` specs
 * take the bytes verbatim; `json`/`jsonc` specs parse the file (comments
 * allowed — templates are hand-written).
 */
async function readTemplate(
  root: string,
  label: string,
  template: string,
  format: FileFormat,
  errors: string[],
): Promise<JsonValue | string | null> {
  if (typeof template !== 'string' || template.length === 0) {
    errors.push(`${label}: "template" must be a non-empty repo-relative path`);
    return null;
  }
  const target = path.resolve(root, template);
  const rootDir = path.resolve(root);
  if (path.isAbsolute(template) || !target.startsWith(rootDir + path.sep)) {
    errors.push(
      `${label}: template "${template}" must stay inside the repository`,
    );
    return null;
  }
  let text: string;
  try {
    text = await readFile(target, 'utf8');
  } catch {
    errors.push(`${label}: template "${template}" not found`);
    return null;
  }
  if (format === 'text') {
    return text;
  }
  try {
    return parseJsonc(text, `template "${template}"`);
  } catch (e) {
    errors.push(`${label}: ${(e as Error).message}`);
    return null;
  }
}

/**
 * Replace every `template` reference (spec-level for `default`, or per-rule
 * for `value`) with the file content, before compilation. `template: null`
 * means the same as a null value (opt-in base / opt-out rule).
 */
export async function resolveTemplates(
  input: LoomConfigInput,
  root: string,
  sourceLabel = 'config',
): Promise<LoomConfigInput> {
  if (!isPlainObject(input) || !isPlainObject(input.files)) {
    return input; // compileConfig reports top-level shape errors
  }
  const errors: string[] = [];
  const files: Record<string, FileSpecInput> = {};
  for (const [name, spec] of Object.entries(input.files)) {
    if (!isPlainObject(spec)) {
      files[name] = spec;
      continue;
    }
    const label = `files["${name}"]`;
    const format = spec.format ?? defaultFormatFor(name);
    const next: Record<string, unknown> = { ...spec };
    if ('template' in next) {
      const template = next.template;
      delete next.template;
      if (template === null || template === undefined) {
        if ('default' in next) {
          errors.push(
            `${label}: "template: null" conflicts with a "default" prop`,
          );
        } else {
          next.default = null;
        }
      } else if ('default' in next) {
        errors.push(
          `${label}: "template" and "default" are mutually exclusive`,
        );
      } else {
        next.default = await readTemplate(
          root,
          label,
          template as string,
          format,
          errors,
        );
      }
    }
    if (Array.isArray(next.rules)) {
      const resolved: unknown[] = [];
      for (const [index, rule] of (next.rules as RuleInput[]).entries()) {
        if (!isPlainObject(rule) || !('template' in rule)) {
          resolved.push(rule);
          continue;
        }
        const entry: Record<string, unknown> = { ...rule };
        const template = entry.template;
        delete entry.template;
        const ruleLabel = `${label} rules[${index}]`;
        if (template === null || template === undefined) {
          if ('value' in entry) {
            errors.push(
              `${ruleLabel}: "template: null" conflicts with a "value" prop`,
            );
          } else {
            entry.value = null;
          }
        } else if ('value' in entry) {
          errors.push(
            `${ruleLabel}: "template" and "value" are mutually exclusive`,
          );
        } else {
          entry.value = await readTemplate(
            root,
            ruleLabel,
            template as string,
            format,
            errors,
          );
        }
        resolved.push(entry);
      }
      next.rules = resolved;
    }
    files[name] = next;
  }
  if (errors.length > 0) {
    throw new LoomError(`${sourceLabel}:\n  - ${errors.join('\n  - ')}`);
  }
  return { ...input, files };
}

/** Every template path referenced by a raw config input, sorted. */
export function collectTemplatePaths(input: unknown): string[] {
  if (!isPlainObject(input) || !isPlainObject(input.files)) {
    return [];
  }
  const found = new Set<string>();
  for (const spec of Object.values(input.files)) {
    if (!isPlainObject(spec)) {
      continue;
    }
    const template = (spec as { template?: unknown }).template;
    if (typeof template === 'string' && template.length > 0) {
      found.add(template);
    }
    const rules = (spec as { rules?: unknown }).rules;
    if (Array.isArray(rules)) {
      for (const rule of rules) {
        if (!isPlainObject(rule)) {
          continue;
        }
        const ruleTemplate = (rule as { template?: unknown }).template;
        if (typeof ruleTemplate === 'string' && ruleTemplate.length > 0) {
          found.add(ruleTemplate);
        }
      }
    }
  }
  return [...found].sort();
}

/** Locate and load config-loom.yaml from the repo root. */
export async function loadConfig(
  root: string,
  explicitPath?: string,
): Promise<{ config: LoomConfig; path: string }> {
  const candidates = explicitPath
    ? [explicitPath]
    : DEFAULT_CONFIG_FILENAMES.map((name) => `${root}/${name}`);
  for (const candidate of candidates) {
    let text: string;
    try {
      text = await readFile(candidate, 'utf8');
    } catch {
      continue;
    }
    const parsed = parseYaml(text, { prettyErrors: true }) as unknown;
    const resolved = await resolveTemplates(
      parsed as LoomConfigInput,
      root,
      candidate,
    );
    const config = compileConfig(resolved, candidate);
    return { config, path: candidate };
  }
  throw new LoomError(
    `no loom configuration found (looked for: ${candidates.join(', ')}) — run 'config-loom init' first`,
  );
}
