function longestCommonSuffix(values: string[]): string {
  if (values.length === 0) {
    return '';
  }
  const first = values[0] as string;
  let suffix = '';
  for (let i = 1; i <= first.length; i += 1) {
    const candidate = first.slice(first.length - i);
    if (values.every((value) => value.endsWith(candidate))) {
      suffix = candidate;
    } else {
      break;
    }
  }
  return suffix;
}

function longestCommonPrefix(values: string[]): string {
  if (values.length === 0) {
    return '';
  }
  const first = values[0] as string;
  let prefix = '';
  for (let i = 1; i <= first.length; i += 1) {
    const candidate = first.slice(0, i);
    if (values.every((value) => value.startsWith(candidate))) {
      prefix = candidate;
    } else {
      break;
    }
  }
  return prefix;
}

/**
 * Trim a common name prefix up to (and including) its last name boundary,
 * so `capacitor-` beats `c`: the wildcard then extends along the name family
 * instead of arbitrary characters.
 */
function boundaryPrefix(head: string): string {
  for (let i = head.length - 1; i >= 0; i -= 1) {
    const char = head[i];
    if (char === '-' || char === '_' || char === '.') {
      return head.slice(0, i + 1);
    }
  }
  return '';
}

function parentOf(workspace: string): string {
  const cut = workspace.lastIndexOf('/');
  return cut === -1 ? '' : workspace.slice(0, cut);
}

function nameOf(workspace: string): string {
  const cut = workspace.lastIndexOf('/');
  return cut === -1 ? workspace : workspace.slice(cut + 1);
}

function sameSet(a: string[], b: string[]): boolean {
  if (a.length !== b.length) {
    return false;
  }
  const set = new Set(a);
  return b.every((value) => set.has(value));
}

/**
 * Translate the pnpm-workspace glob shapes that pattern synthesis understands
 * into regex source: `apps/*` -> `apps/[^/]+`, `apps/**` -> `apps(?:/.*)?`.
 * Returns null for anything cleverer (those stay out of the candidates).
 */
export function globToRegExpSource(glob: string): string | null {
  const match = /^(.*?)\/(\*\*|\*)$/.exec(glob);
  if (!match) {
    if (glob === '**') {
      return '.*';
    }
    if (glob === '*') {
      return '[^/]+';
    }
    return null;
  }
  const base = escapeRegExp(match[1] as string);
  return match[2] === '*' ? `${base}/[^/]+` : `${base}(?:/.*)?`;
}

/** Hyphen-aligned trailing token groups: `a-b-c` -> ['c', 'b-c'] (keys for `.*-KEY`). */
function alignedSuffixes(name: string): string[] {
  const parts = name.split('-');
  const out: string[] = [];
  for (let i = parts.length - 1; i > 0; i--) {
    out.push(parts.slice(i).join('-'));
  }
  return out;
}

/** Hyphen-aligned leading token groups ending at a boundary: `a-b` -> ['a-']. */
function alignedPrefixes(name: string): string[] {
  const parts = name.split('-');
  const out: string[] = [];
  for (let i = 1; i < parts.length; i++) {
    out.push(`${parts.slice(0, i).join('-')}-`);
  }
  return out;
}

/**
 * The family key shared by the most names (>= 2), preferring longer keys on
 * ties; keys shorter than `minLength` are ignored.
 */
function bestFamily(keysPerName: string[][], minLength: number): string | null {
  const counts = new Map<string, number>();
  for (const keys of keysPerName) {
    for (const key of new Set(keys)) {
      if (key.length >= minLength) {
        counts.set(key, (counts.get(key) ?? 0) + 1);
      }
    }
  }
  let best: string | null = null;
  let bestCount = 1;
  for (const [key, count] of counts) {
    if (
      count > bestCount ||
      (count === bestCount && best !== null && key.length > best.length)
    ) {
      best = key;
      bestCount = count;
    }
  }
  return bestCount >= 2 ? best : null;
}

/** Minimal meaningful text (delimiter included) for a broad shape tail/head
 * — `-rs`, `mq-` qualify; raw character fragments do not. */
const BROAD_SHAPE_MIN = 3;

/**
 * The most promising delimiter-anchored broad regex over a set of paths:
 * tails like `.*-rs`, heads like `mq-.*`. Every delimiter position of every
 * remaining path yields at most two candidates (each a whole token, never
 * a character fragment); each candidate is validated once against the full
 * workspace set — touching a `present` workspace rejects it — then ranked
 * by remaining coverage (desc) and pattern length (asc). Total cost is
 * linear in the combined path length, so running it per exclusion round is
 * cheap even for large workspaces.
 */
function bestBroadShape(
  remaining: string[],
  allWorkspaces: string[],
  present: Set<string>,
): string | null {
  let best: { pattern: string; coverage: number } | null = null;
  const seen = new Set<string>();
  for (const ws of remaining) {
    for (let i = 0; i < ws.length; i++) {
      // Naming boundaries only (`-`, `_`, `.`): `/`-anchored shapes are the
      // directory logic's job and crossing directories silently would make
      // `.*\/ui` swallow a future `apps/ui` that should get the file.
      if (/[a-zA-Z0-9/]/.test(ws[i] as string)) {
        continue;
      }
      const candidates: Array<[string, number]> = [
        [`.*${escapeRegExp(ws.slice(i))}`, ws.length - i],
        [`${escapeRegExp(ws.slice(0, i + 1))}.*`, i + 1],
      ];
      for (const [candidate, textLength] of candidates) {
        if (seen.has(candidate) || textLength < BROAD_SHAPE_MIN) {
          continue;
        }
        seen.add(candidate);
        const regex = new RegExp(`^(?:${candidate})$`);
        if (
          allWorkspaces.some((other) => present.has(other) && regex.test(other))
        ) {
          continue;
        }
        let coverage = 0;
        for (const other of remaining) {
          if (regex.test(other)) {
            coverage++;
          }
        }
        if (coverage === 0) {
          continue;
        }
        if (
          best === null ||
          coverage > best.coverage ||
          (coverage === best.coverage && candidate.length < best.pattern.length)
        ) {
          best = { pattern: candidate, coverage };
        }
      }
    }
  }
  return best?.pattern ?? null;
}

/**
 * Collapse workspaces that LACK a file into a few directory/naming-family
 * regexes usable as a file-level `exclude` list (see FileSpecInput.exclude).
 *
 * A candidate is only accepted when it matches none of the `present`
 * workspaces — the exclusion can never swallow a project that has the file
 * today. Families are discovered from hyphen-aligned name tokens
 * (`packages/mq-.*`, `packages/.*-medicine-quotation-sdk`), from broad
 * delimiter-anchored shapes no 2-member group revealed (`.*-rs`), or from a
 * parent directory whose whole subtree lacks the file. When the missing
 * workspaces cannot be covered compactly the result is `null` and the
 * caller must scope the file with an `include` over its holders instead of
 * enumerating names (drift).
 */
export function synthesizeExclude(
  missing: string[],
  present: Set<string>,
  allWorkspaces: string[],
): string[] | null {
  if (missing.length === 0) {
    return [];
  }
  const remaining = new Set(missing);
  const out: string[] = [];
  const touchesPresent = (regex: RegExp): boolean =>
    allWorkspaces.some((ws) => present.has(ws) && regex.test(ws));
  const accept = (pattern: string): boolean => {
    const regex = new RegExp(`^(?:${pattern})$`);
    if (touchesPresent(regex)) {
      return false;
    }
    let covered = 0;
    for (const ws of remaining) {
      if (regex.test(ws)) {
        remaining.delete(ws);
        covered++;
      }
    }
    if (covered === 0) {
      return false;
    }
    out.push(pattern);
    return true;
  };

  while (remaining.size > 0 && out.length < MAX_EXCLUDE_PATTERNS) {
    const groups = new Map<string, string[]>();
    for (const ws of remaining) {
      const bucket = groups.get(parentOf(ws));
      if (bucket) {
        bucket.push(ws);
      } else {
        groups.set(parentOf(ws), [ws]);
      }
    }
    let progressed = false;
    const ordered = [...groups.entries()].sort(
      (a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]),
    );
    for (const [parent, members] of ordered) {
      if (members.length < 2) {
        continue;
      }
      const names = members.map(nameOf);
      const candidates: string[] = [];
      if (parent !== '') {
        const escParent = escapeRegExp(parent);
        if (
          !allWorkspaces.some(
            (ws) => present.has(ws) && ws.startsWith(`${parent}/`),
          )
        ) {
          candidates.push(`${escParent}/.*`);
        }
        const suffix = bestFamily(
          names.map(alignedSuffixes),
          MIN_SHARED_SUFFIX,
        );
        if (suffix !== null) {
          candidates.push(`${escParent}/.*-${escapeRegExp(suffix)}`);
        }
        const prefix = bestFamily(names.map(alignedPrefixes), 3);
        if (prefix !== null) {
          candidates.push(`${escParent}/${escapeRegExp(prefix)}.*`);
        }
      }
      if (members.length <= MAX_EXCLUDE_ALTERNATION) {
        candidates.push(members.map((ws) => escapeRegExp(ws)).join('|'));
      }
      for (const candidate of candidates) {
        if (accept(candidate)) {
          progressed = true;
          break;
        }
      }
      if (progressed) {
        break;
      }
    }
    if (!progressed) {
      // Broad naming shapes a 2-member group never revealed: delimiter-
      // anchored tails like `.*-rs` or heads like `mq-.*`. An outlier with
      // no sibling today may still head a family — the shape also keeps
      // tomorrow's siblings excluded for free.
      const broad = bestBroadShape([...remaining], allWorkspaces, present);
      if (broad !== null && accept(broad)) {
        progressed = true;
      }
    }
    if (!progressed) {
      break;
    }
  }

  for (const ws of remaining) {
    out.push(escapeRegExp(ws));
  }
  if (out.length > MAX_EXCLUDE_PATTERNS || out.join('').length > 240) {
    return null;
  }
  return out;
}

/** Sort metric for candidate patterns: plain length, handicapping the
 * exclusion guards (see GUARD_HANDICAP) so they only win when clearly
 * shorter; ties go to the wildcard shape (it survives tomorrow's siblings). */
function candidateCost(pattern: string): number {
  const handicap = pattern.startsWith('(?!')
    ? ROOT_GUARD_HANDICAP
    : pattern.includes('(?!')
      ? GUARD_HANDICAP
      : 0;
  return pattern.length + handicap;
}

function rankCandidates(a: string, b: string): number {
  return (
    candidateCost(a) - candidateCost(b) ||
    (a.includes('*') ? 0 : 1) - (b.includes('*') ? 0 : 1)
  );
}

/**
 * Shapes for a group of members sharing one parent directory, loosest first:
 * - whole subtree covered -> `dir/.*`;
 * - directory minus a few siblings -> `dir/(?!ex1$|ex2$).*` — keeps matching
 *   when new projects join the directory, which is exactly what a long name
 *   list can never do;
 * - the explicit (non-capturing) name list as the tight fallback.
 */
function scopedGroupCandidates(
  parent: string,
  memberPaths: string[],
  allWorkspaces: string[],
): string[] {
  const rawPrefix = parent === '' ? '' : `${parent}/`;
  const escParent = parent === '' ? '' : `${escapeRegExp(parent)}/`;
  const memberSet = new Set(memberPaths);
  const exceptions: string[] = [];
  for (const workspace of allWorkspaces) {
    if (!memberSet.has(workspace) && workspace.startsWith(rawPrefix)) {
      exceptions.push(workspace.slice(rawPrefix.length));
    }
  }
  const out: string[] = [];
  if (exceptions.length === 0) {
    out.push(`${escParent}.*`);
  } else if (
    exceptions.length <= memberPaths.length &&
    exceptions.length <= MAX_EXCLUSION_EXCEPTIONS
  ) {
    out.push(
      `${escParent}(?!${exceptions
        .map((exc) => `${escapeRegExp(exc)}$`)
        .join('|')}).*`,
    );
  }
  const names = memberPaths.map(nameOf);
  out.push(
    names.length === 1
      ? `${escParent}${escapeRegExp(names[0] as string)}`
      : `${escParent}(?:${names.map((name) => escapeRegExp(name)).join('|')})`,
  );
  return out;
}

/**
 * Join per-directory components with `|`, factoring the shared directory
 * prefix once (`libs/(?:domain/x|shared/y)`) so long trees stay readable.
 * When no common prefix spans every component the factoring recurses one
 * directory level down (components under `libs/` collapse even while an
 * unrelated `apps/.*` stands apart).
 */
function factorCommonDirectory(components: string[]): string {
  if (components.length < 2) {
    return components[0] as string;
  }
  const joined = components.join('|');
  const lcp = longestCommonPrefix(components);
  const cut = lcp.lastIndexOf('/');
  if (cut > 0) {
    const head = lcp.slice(0, cut);
    if (!components.some((component) => component.length <= head.length + 1)) {
      const rests = components.map((component) =>
        component.slice(head.length + 1),
      );
      return `${head}/(?:${rests.join('|')})`;
    }
    return joined;
  }
  const buckets = new Map<string, string[]>();
  for (const component of components) {
    const slash = component.indexOf('/');
    if (slash <= 0) {
      return joined;
    }
    const key = component.slice(0, slash);
    const bucket = buckets.get(key);
    if (bucket) {
      bucket.push(component);
    } else {
      buckets.set(key, [component]);
    }
  }
  if (buckets.size === components.length) {
    return joined;
  }
  return [...buckets.values()]
    .map((bucket) => factorCommonDirectory(bucket))
    .join('|');
}

/**
 * Key for a cluster spanning several parent directories: every directory
 * contributes its own best shape (`apps/.*|libs/(?:adapters/.*|shared/(?:a|b))`)
 * instead of the whole cluster collapsing into one long full-path alternation.
 */
function compositeCandidate(
  members: string[],
  allWorkspaces: string[],
): string | null {
  const groups = new Map<string, string[]>();
  for (const member of members) {
    const parent = parentOf(member);
    const bucket = groups.get(parent);
    if (bucket) {
      bucket.push(member);
    } else {
      groups.set(parent, [member]);
    }
  }
  if (groups.size < 2) {
    return null;
  }
  const components: string[] = [];
  for (const [parent, memberPaths] of groups) {
    const shapes = scopedGroupCandidates(parent, memberPaths, allWorkspaces);
    shapes.sort(rankCandidates);
    components.push(shapes[0] as string);
  }
  return factorCommonDirectory(components);
}

/**
 * Cluster that covers (nearly) the whole repository: `(?!ex1$|ex2$).*` — the
 * most compact key for "everything but these few".
 */
function globalExclusionCandidate(
  members: string[],
  allWorkspaces: string[],
): string | null {
  const memberSet = new Set(members);
  const exceptions = allWorkspaces.filter((ws) => !memberSet.has(ws));
  if (
    exceptions.length === 0 ||
    exceptions.length >= members.length ||
    exceptions.length > MAX_EXCLUSION_EXCEPTIONS
  ) {
    return null;
  }
  return `(?!${exceptions.map((exc) => `${escapeRegExp(exc)}$`).join('|')}).*`;
}

/**
 * Derive a regex for a cluster that matches EXACTLY its members among all
 * current workspaces. Candidates, shortest first: shared parent dir + name
 * alternation, common name suffix/prefix, whole-directory shapes
 * (`P/[^/]+`, `P/.*`), directory-minus-few-siblings guards, a per-directory
 * composite for clusters spanning several dirs, a root-level exclusion for
 * near-total coverage, and pnpm workspace globs translated to regex. Only
 * patterns validated against the current workspace set are accepted, so the
 * result never over-matches TODAY; the directory-shaped candidates are the
 * point because they keep matching TOMORROW, when a new project joins the
 * shape.
 */
export function synthesizePattern(
  members: string[],
  allWorkspaces: string[],
  globs: string[] = [],
): string {
  const alternation = members.map((member) => escapeRegExp(member)).join('|');
  if (members.length < 2) {
    return alternation;
  }
  const candidates: string[] = [alternation];

  for (const glob of globs) {
    if (glob.startsWith('!')) {
      continue;
    }
    const source = globToRegExpSource(glob);
    if (source !== null) {
      candidates.push(source);
    }
  }

  // Whole-subtree shape: when every workspace below the members' common
  // directory is a member, use `<dir>/.*` — future (even nested) members of
  // that directory join the rule without anyone editing it.
  const commonDir = longestCommonPrefix(members);
  const cut = commonDir.lastIndexOf('/');
  if (cut > 0) {
    const head = commonDir.slice(0, cut);
    if (
      members.every((ws) => ws.startsWith(`${head}/`)) &&
      sameSet(
        allWorkspaces.filter((ws) => ws.startsWith(`${head}/`)),
        members,
      )
    ) {
      candidates.push(`${escapeRegExp(head)}/.*`);
    }
  }

  const dirs = members.map((member) => parentOf(member));
  const prefix = dirs[0] as string;
  if (dirs.every((dir) => dir === prefix)) {
    const names = members.map((member) => nameOf(member));
    if (prefix !== '') {
      candidates.push(
        `${prefix}/(?:${names.map((name) => escapeRegExp(name)).join('|')})`,
      );
    }
    const suffix = longestCommonSuffix(names);
    if (
      suffix !== '' &&
      suffix.length >= MIN_SHARED_SUFFIX &&
      names.every((name) => name !== suffix)
    ) {
      candidates.push(
        `${prefix !== '' ? `${prefix}/` : ''}.*${escapeRegExp(suffix)}`,
      );
    }
    const head = boundaryPrefix(longestCommonPrefix(names));
    if (
      head !== '' &&
      head.length >= MIN_SHARED_PREFIX &&
      names.every((name) => name !== head)
    ) {
      candidates.push(
        `${prefix !== '' ? `${prefix}/` : ''}${escapeRegExp(head)}.*`,
      );
    }
    if (prefix !== '') {
      if (
        sameSet(
          allWorkspaces.filter((ws) => parentOf(ws) === prefix),
          members,
        )
      ) {
        candidates.push(`${prefix}/[^/]+`);
      }
      if (
        sameSet(
          allWorkspaces.filter((ws) => ws.startsWith(`${prefix}/`)),
          members,
        )
      ) {
        candidates.push(`${prefix}/.*`);
      }
    }
    for (const shape of scopedGroupCandidates(prefix, members, allWorkspaces)) {
      candidates.push(shape);
    }
  } else {
    const composite = compositeCandidate(members, allWorkspaces);
    if (composite !== null) {
      candidates.push(composite);
    }
  }
  const globalExclusion = globalExclusionCandidate(members, allWorkspaces);
  if (globalExclusion !== null) {
    candidates.push(globalExclusion);
  }
  candidates.sort(rankCandidates);
  for (const candidate of candidates) {
    const regex = new RegExp(`^(?:${candidate})$`);
    const matched = allWorkspaces.filter((workspace) => regex.test(workspace));
    if (sameSet(matched, members)) {
      return candidate;
    }
  }
  return alternation;
}

function isEmptyPatch(value: JsonValue): boolean {
  return isPlainObject(value) && Object.keys(value).length === 0;
}

/**
 * `tsconfig.json`, `tsconfig.build.json`, `jsconfig.json` … — files whose
 * path-like values follow TypeScript semantics, where `./dist` and `dist`
 * (or `src` and `src` plus a recursive glob) address the same thing.
 */
function isTsConfigName(file: string): boolean {
  return /^(?:ts|js)config(?:\..+)?\.json$/.test(file);
}

function uniquePattern(
  rules: Record<string, JsonValue | string | null>,
  members: string[],
  workspaces: string[],
  globs: string[],
): string {
  let pattern = synthesizePattern(members, workspaces, globs);
  if (Object.prototype.hasOwnProperty.call(rules, pattern)) {
    pattern = members.map((member) => escapeRegExp(member)).join('|');
  }
  return pattern;
}

function clusterValue(
  cluster: Cluster,
  format: FileFormat,
): JsonValue | string {
  if (format === 'text') {
    return cluster.normalized;
  }
  return structuredClone(cluster.parsed);
}

async function readOrNull(target: string): Promise<string | null> {
  try {
    return await readFile(target, 'utf8');
  } catch {
    return null;
  }
}

/**
 * Reverse-engineer a loom configuration from the files scattered across
 * the workspace: cluster every file by canonical content, take the most
 * frequent cluster as `default` (when coverage is complete) and derive
 * delta rules for the exceptions.
 */
export async function buildPlan(
  root: string,
  opts: InitOptions = {},
): Promise<InitPlan> {
  const workspaces = await discoverWorkspaces(root, [], opts.runner);
  const globs = opts.globs ?? (await readWorkspaceGlobs(root));
  const requested = opts.files ?? KNOWN_CONFIG_FILES;

  const config: LoomConfigInput = { files: {} };
  const managedEntries: Array<{ workspace: string; file: string }> = [];
  const clusters: ClusterInfo[] = [];
  const unmanaged: InitPlan['unmanaged'] = [];

  for (const file of requested) {
    let format = defaultFormatFor(file);
    const byHash = new Map<string, Cluster>();
    const present = new Set<string>();
    for (const workspace of workspaces) {
      const raw = await readOrNull(path.join(root, workspace, file));
      if (raw === null) {
        continue;
      }
      present.add(workspace);
      let normalized: string;
      let parsed: JsonValue | null = null;
      if (format === 'text') {
        normalized = normalizeText(raw);
      } else {
        try {
          parsed = parseJsonc(raw, path.join(workspace, file));
        } catch (e) {
          unmanaged.push({ workspace, file, reason: (e as Error).message });
          continue;
        }
        if (format === 'json') {
          try {
            JSON.parse(raw);
          } catch {
            // the project writes this file with comments or trailing
            // commas — respect that idiom instead of forcing strict JSON.
            format = 'jsonc';
          }
        }
        if (!isPlainObject(parsed)) {
          unmanaged.push({
            workspace,
            file,
            reason: 'top-level JSON value is not an object',
          });
          parsed = null;
          continue;
        }
        normalized = canonicalJson(parsed);
      }
      let cluster = byHash.get(normalized);
      if (!cluster) {
        cluster = { normalized, members: [], parsed };
        byHash.set(normalized, cluster);
      }
      cluster.members.push(workspace);
    }

    if (byHash.size === 0) {
      continue;
    }

    const sorted = [...byHash.values()].sort(
      (a, b) =>
        b.members.length - a.members.length ||
        (a.members[0] as string).localeCompare(b.members[0] as string),
    );
    const fullCoverage = present.size === workspaces.length;
    const mode = sorted[0] as Cluster;
    const missing = workspaces.filter((ws) => !present.has(ws));

    const rules: Record<string, JsonValue | string | null> = {};
    let fileExclude: string[] | undefined;

    // Sparse files (some workspaces lack them) are SCOPED, never opted-in
    // with a null default: prefer a compact `exclude` family (new projects
    // joining the default shape inherit the file automatically, ones
    // joining an excluded family are ignored for free); fall back to an
    // `include` over the holders when the missing set is scattered and no
    // family covers it.
    const excluded = fullCoverage
      ? []
      : synthesizeExclude(missing, present, workspaces);
    const includePattern =
      !fullCoverage && excluded === null
        ? synthesizePattern([...present], workspaces, globs)
        : undefined;

    if (format === 'text') {
      // Text has no merge semantics: the default applies wholesale to
      // every workspace in scope; later rules replace it entirely.
      rules.default = mode.normalized;
      clusters.push({
        file,
        pattern: 'default',
        members: [...mode.members],
        kind: 'default',
      });
      for (const cluster of sorted.slice(1)) {
        const pattern = uniquePattern(
          rules,
          cluster.members,
          workspaces,
          globs,
        );
        rules[pattern] = cluster.normalized;
        clusters.push({
          file,
          pattern,
          members: [...cluster.members],
          kind: 'full',
        });
      }
      if (excluded && excluded.length > 0) {
        fileExclude = excluded;
        clusters.push({
          file,
          pattern: excluded.join(' | '),
          members: [...missing],
          kind: 'excluded',
        });
      }
    } else {
      // JSON/JSONC: `default` is the common base (always present — scope
      // comes from `include`/`exclude`, never from a null default); every
      // matching rule deep-merges on top of it, so specific props win.
      rules.default = clusterValue(mode, format);
      const deltaBase = mode.parsed;
      clusters.push({
        file,
        pattern: 'default',
        members: [...mode.members],
        kind: 'default',
      });
      for (const cluster of sorted) {
        if (cluster === mode) {
          continue;
        }
        let value: JsonValue;
        let kind: ClusterInfo['kind'];
        if (deltaBase !== null && cluster.parsed !== null) {
          const delta = computeDelta(
            deltaBase,
            cluster.parsed,
            isTsConfigName(file) ? tsconfigEqual : undefined,
          );
          if (delta.kind !== 'delta') {
            value = structuredClone(cluster.parsed);
            kind = 'full';
          } else if (isEmptyPatch(delta.value)) {
            // The default already describes this cluster completely.
            clusters.push({
              file,
              pattern: 'default',
              members: [...cluster.members],
              kind: 'default',
            });
            continue;
          } else {
            value = delta.value;
            kind = 'delta';
          }
        } else {
          value = structuredClone(cluster.parsed);
          kind = 'full';
        }
        const pattern = uniquePattern(
          rules,
          cluster.members,
          workspaces,
          globs,
        );
        rules[pattern] = value;
        clusters.push({
          file,
          pattern,
          members: [...cluster.members],
          kind,
        });
      }
      if (excluded && excluded.length > 0) {
        fileExclude = excluded;
        clusters.push({
          file,
          pattern: excluded.join(' | '),
          members: [...missing],
          kind: 'excluded',
        });
      }
    }

    // `default` is emitted as a spec property ABOVE `rules` — never as a
    // pattern — so a workspace folder literally named `default` can be
    // matched by a rule. Sparse coverage rides on `include` (holders) or
    // `exclude` (missing families), never on a null default.
    const spec: FileSpecInput = {
      format,
      arrays: 'replace',
      ...(includePattern !== undefined ? { include: includePattern } : {}),
      default: rules['default'],
      rules: Object.entries(rules)
        .filter(([pattern]) => pattern !== 'default')
        .map(([pattern, value]) => ({ pattern, value })),
    };
    if (fileExclude && fileExclude.length > 0) {
      spec.exclude = fileExclude;
    }
    config.files[file] = spec;
    for (const cluster of sorted) {
      for (const member of cluster.members) {
        managedEntries.push({ workspace: member, file });
      }
    }
    // Files that exist but could not be parsed are still taken over (sync
    // regenerates them from the default) — otherwise they would stay
    // tracked and permanently dirty.
    for (const entry of unmanaged) {
      if (entry.file === file && present.has(entry.workspace)) {
        managedEntries.push({ workspace: entry.workspace, file });
      }
    }
  }

  if (Object.keys(config.files).length === 0) {
    throw new LoomError(
      `no managed configuration file found in ${workspaces.length} workspace(s) (looked for: ${requested.join(', ')})`,
    );
  }

  const seen = new Set<string>();
  const managedFiles: string[] = [];
  for (const entry of managedEntries) {
    const target = path.posix.join(entry.workspace, entry.file);
    if (!seen.has(target)) {
      seen.add(target);
      managedFiles.push(target);
    }
  }

  return {
    config,
    managedFiles: managedFiles.sort(),
    managedEntries: managedEntries
      .filter(
        (entry, index, all) =>
          all.findIndex(
            (other) =>
              other.workspace === entry.workspace && other.file === entry.file,
          ) === index,
      )
      .sort(
        (a, b) =>
          a.workspace.localeCompare(b.workspace) ||
          a.file.localeCompare(b.file),
      ),
    clusters,
    unmanaged,
    workspaces,
  };
}

export function serializeConfig(config: LoomConfigInput): string {
  const header = [
    '# Managed by config-loom.',
    '# Each `files:` entry writes one workspace file. The entry key names',
    '# it; `filename:` sets the target file (default: the key), so several',
    '# entries may share one filename to serve different workspace subsets',
    '# — for a workspace, the FIRST entry whose `include` matches and whose',
    '# `exclude` does not is the one that renders. `include` and `exclude`',
    '# take one regular expression or a list, matched full against the',
    '# workspace directory path; omit `include` to cover every workspace.',
    '# `default:` is the required base content of the entry. Each rule is a',
    '# `pattern` (same regex syntax) and a `value`. Order matters: rules',
    '# merge over default and each other, top to bottom, later rules win.',
    '# A null INSIDE a rule value removes an inherited key (JSON Merge',
    '# Patch, RFC 7386). For json/jsonc, values are written as plain',
    '# JSON/JSONC text block scalars — JSON stays readable as JSON. Prefer',
    '# families (`libs/.*`, `.*-rs`) over name lists, so new projects',
    '# joining a shape need no edit here. Instead of an inline value,',
    '# `template: <repo-relative path>` pulls content from a file',
    "# (multiline text or commented JSONC). After editing, run 'config-loom",
    "# sync' (or any turbo command, once wired).",
  ].join('\n');
  const jsonText = (value: JsonValue): string =>
    `${JSON.stringify(value, null, 2)}\n`;
  const wireValue = (
    value: JsonValue | string,
    format: FileFormat,
  ): JsonValue | string =>
    format !== 'text' && isPlainObject(value) ? jsonText(value) : value;
  const files: Record<string, unknown> = {};
  for (const [name, spec] of Object.entries(config.files)) {
    const target = spec.filename ?? name;
    const format = spec.format ?? defaultFormatFor(target);
    const out: Record<string, unknown> = {};
    if (spec.filename !== undefined) {
      out.filename = spec.filename;
    }
    if (spec.format !== undefined) {
      out.format = spec.format;
    }
    if (spec.arrays !== undefined) {
      out.arrays = spec.arrays;
    }
    if (spec.banner !== undefined) {
      out.banner = spec.banner;
    }
    if (spec.include !== undefined) {
      out.include = spec.include;
    }
    if (spec.default !== undefined) {
      out.default = wireValue(spec.default, format);
    }
    if (spec.rules !== undefined && spec.rules.length > 0) {
      out.rules = spec.rules.map((rule) => ({
        pattern: rule.pattern,
        value:
          rule.value === undefined ? undefined : wireValue(rule.value, format),
      }));
    }
    if (spec.exclude !== undefined) {
      out.exclude = spec.exclude;
    }
    files[name] = out;
  }
  const wire: Record<string, unknown> = {};
  if (config.exclude && config.exclude.length > 0) {
    wire.exclude = config.exclude;
  }
  wire.files = files;
  return `${header}\n${stringify(wire, { lineWidth: 0, indent: 2 })}`;
}

async function findExistingConfig(root: string): Promise<string | null> {
  for (const name of DEFAULT_CONFIG_FILENAMES) {
    const candidate = path.join(root, name);
    try {
      await access(candidate);
      return candidate;
    } catch {
      // keep looking
    }
  }
  return null;
}

/** Pre-YAML JSON configs: no longer read, only removed by init (conversion). */
const LEGACY_CONFIG_NAMES = ['config-loom.jsonc', 'config-loom.json'];

async function findLegacyConfig(root: string): Promise<string | null> {
  for (const name of LEGACY_CONFIG_NAMES) {
    const candidate = path.join(root, name);
    try {
      await access(candidate);
      return candidate;
    } catch {
      // keep looking
    }
  }
  return null;
}

async function ask(question: string): Promise<string> {
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  return await new Promise<string>((resolve) => {
    rl.question(question, (answer) => {
      rl.close();
      resolve(answer.trim());
    });
  });
}

/**
 * Full init flow: build the plan, write config-loom.yaml (converting a
 * legacy JSON config), drop the scattered
 * originals from git and disk, add them to .gitignore and regenerate
 * everything with sync.
 */
export async function initRepo(
  root: string,
  opts: InitOptions = {},
): Promise<InitResult> {
  const existing = await findExistingConfig(root);
  const legacy = existing === null ? await findLegacyConfig(root) : null;
  const occupied = existing ?? legacy;
  if (occupied && !opts.force && !opts.dryRun) {
    throw new LoomError(
      `${occupied} already exists — re-run with --force to overwrite it (a legacy JSON config is converted to YAML)`,
    );
  }
  const plan = await buildPlan(root, opts);
  const globs = opts.globs ?? (await readWorkspaceGlobs(root));
  // The canonical name is always the YAML one; a legacy JSON config found
  // on disk is converted (rewritten below, then removed).
  const configPath = path.join(root, DEFAULT_CONFIG_FILENAMES[0] as string);

  if (opts.dryRun) {
    const gitRepo = await isGitRepo(root);
    const tracked = gitRepo ? await listTrackedFiles(root) : new Set<string>();
    return {
      plan,
      configPath,
      gitRepo,
      wire: opts.noWire
        ? null
        : await wireRepo(root, {
            outputs: deriveOutputs(
              plan.workspaces,
              Object.keys(plan.config.files),
            ),
            dryRun: true,
          }),
      untracked: plan.managedFiles.filter((file) => tracked.has(file)),
      ignorePatterns: synthesizeIgnoreList(plan.managedEntries, globs, tracked),
    };
  }

  if (!opts.yes && plan.managedFiles.length > 0) {
    if (!process.stdin.isTTY) {
      throw new LoomError(
        `init will delete and regenerate ${plan.managedFiles.length} existing file(s) — re-run with --yes to confirm`,
      );
    }
    const answer = await ask(
      `Delete ${plan.managedFiles.length} existing config file(s) and manage them via ${configPath}? [y/N] `,
    );
    if (!/^y(es)?$/i.test(answer)) {
      throw new LoomError('aborted');
    }
  }

  await writeFile(configPath, serializeConfig(plan.config), 'utf8');
  // Conversion: drop the legacy JSON config once the YAML one is in place.
  const legacyRel = legacy === null ? null : path.relative(root, legacy);
  if (legacyRel !== null) {
    await unlink(legacy as string).catch(() => undefined);
  }

  const gitRepo = await isGitRepo(root);
  let untracked: string[] = [];
  let ignorePatterns: string[] = [];
  if (gitRepo) {
    const tracked = await listTrackedFiles(root);
    untracked = plan.managedFiles.filter((file) => tracked.has(file));
    if (legacyRel !== null && tracked.has(legacyRel)) {
      untracked = [...untracked, legacyRel];
    }
    await untrackFiles(root, untracked);
    ignorePatterns = synthesizeIgnoreList(plan.managedEntries, globs, tracked);
    await updateGitignoreBlock(root, ignorePatterns);
  }

  if (!opts.keep) {
    for (const file of plan.managedFiles) {
      await unlink(path.join(root, file)).catch(() => undefined);
    }
  }

  const config = compileConfig(plan.config, configPath);
  const sync = await syncAll(config, root);
  const wire = opts.noWire
    ? null
    : await wireRepo(root, {
        outputs: deriveOutputs(plan.workspaces, Object.keys(config.files)),
      });
  return { plan, configPath, gitRepo, untracked, ignorePatterns, sync, wire };
}
