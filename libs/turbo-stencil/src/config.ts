import { StencilError } from './errors';
import { parseJsonc } from './jsonc';
import { isPlainObject } from './util';
import { readFile } from 'node:fs/promises';
import { isAbsolute } from 'node:path';
import type {
  ArrayPolicy,
  CompiledFileEntry,
  CompiledRule,
  FileFormat,
  JsonValue,
  StencilConfig,
  StencilConfigInput,
} from './types';

/**
 * Files turbo-stencil refuses to generate, whatever the config says. pnpm and
 * the tooling itself own these — generating them from a template would break
 * workspace resolution itself.
 */
export const FORBIDDEN_BASENAMES = new Set([
  'package.json',
  'pnpm-workspace.yaml',
  'pnpm-workspace.json5',
  'pnpm-lock.yaml',
  'package-lock.json',
  'yarn.lock',
  'turbo.json',
  'stencil.json',
  'stencil.config.json',
  'stencil.config.jsonc',
  '.gitignore',
  '.npmrc',
]);

export const DEFAULT_CONFIG_FILENAMES = [
  'stencil.json',
  'stencil.config.json',
  'stencil.config.jsonc',
];

const DEFAULT_BANNER_TEXT =
  "Generated by turbo-stencil — do not edit by hand. Change stencil.json and run 'stencil sync'.";

const FORMATS = new Set<FileFormat>(['json', 'jsonc', 'text']);
const ARRAY_POLICIES = new Set<ArrayPolicy>(['replace', 'concat', 'unique']);

export function defaultFormatFor(file: string): FileFormat {
  return file.endsWith('.json') ? 'jsonc' : 'text';
}

function resolveBanner(
  file: string,
  format: FileFormat,
  banner: string | boolean | undefined,
  errors: string[],
): string | false {
  if (banner === undefined || banner === true) {
    if (format === 'jsonc') {
      return `/* ${DEFAULT_BANNER_TEXT} */`;
    }
    if (banner === true && format === 'text') {
      errors.push(
        `files["${file}"]: "banner": true is not supported for text files — provide the banner string explicitly (with its own comment syntax) or omit it`,
      );
    }
    return false;
  }
  if (banner === false) {
    return false;
  }
  if (typeof banner !== 'string') {
    errors.push(`files["${file}"]: "banner" must be a string, true or false`);
    return false;
  }
  if (format === 'json') {
    errors.push(
      `files["${file}"]: "banner" cannot be used with format "json" (comments are not valid JSON) — use format "jsonc" instead`,
    );
    return false;
  }
  return banner;
}

/**
 * Keys are wrapped in a non-capturing group anchored at both ends at match
 * time, so an explicit ^...$ written by the user stays harmless.
 */
export function compileRules(
  file: string,
  format: FileFormat,
  rules: Record<string, JsonValue | string | null>,
  errors: string[],
): Pick<CompiledFileEntry, 'hasDefault' | 'defaultValue' | 'rules'> {
  const compiled: CompiledRule[] = [];
  let hasDefault = false;
  let defaultValue: JsonValue | string | null = null;

  for (const [key, value] of Object.entries(rules)) {
    if (key === 'default') {
      hasDefault = true;
      defaultValue = value;
      if (value === null) {
        continue; // opt-in mode: workspaces only get the file when a rule matches
      }
    } else if (value === null) {
      errors.push(
        `files["${file}"]: rule "${key}" cannot be null — only "default" may be null`,
      );
      continue;
    } else {
      try {
        // Validate the user regex eagerly; matching wraps it anchored later.
        new RegExp(key);
      } catch (e) {
        errors.push(
          `files["${file}"]: rule "${key}" is not a valid regular expression: ${
            (e as Error).message
          }`,
        );
        continue;
      }
    }

    if (format === 'text') {
      if (typeof value !== 'string') {
        errors.push(
          `files["${file}"]: ${key === 'default' ? '"default"' : `rule "${key}"`} must be a string for text files`,
        );
        continue;
      }
    } else if (!isPlainObject(value)) {
      errors.push(
        `files["${file}"]: ${key === 'default' ? '"default"' : `rule "${key}"`} must be an object for ${format} files`,
      );
      continue;
    }

    if (key === 'default') {
      continue; // the base value, not a pattern — never matched as a rule
    }

    compiled.push({
      pattern: key,
      regex: new RegExp(`^(?:${key})$`),
      value,
    });
  }
  if (!hasDefault) {
    errors.push(
      `files["${file}"]: rules must contain a "default" key (use null for opt-in mode)`,
    );
  }

  return { hasDefault, defaultValue, rules: compiled };
}

export function compileConfig(
  input: StencilConfigInput,
  label: string,
): StencilConfig {
  if (!isPlainObject(input)) {
    throw new StencilError(`${label}: expected a JSON object at the top level`);
  }
  const errors: string[] = [];
  if (!isPlainObject(input.files) || Object.keys(input.files).length === 0) {
    throw new StencilError(`${label}: "files" must be a non-empty object`);
  }

  const files: Record<string, CompiledFileEntry> = {};
  for (const [rawName, spec] of Object.entries(input.files)) {
    const file = rawName.replace(/\\/g, '/').replace(/^\.\//, '');
    const basename = file.slice(file.lastIndexOf('/') + 1).toLowerCase();
    if (isAbsolute(file) || file.split('/').includes('..')) {
      errors.push(
        `files["${rawName}"]: must be a relative path without ".." segments`,
      );
      continue;
    }
    if (FORBIDDEN_BASENAMES.has(basename)) {
      errors.push(
        `files["${rawName}"]: "${basename}" can never be generated by turbo-stencil (owned by pnpm/git/tooling itself)`,
      );
      continue;
    }
    if (!isPlainObject(spec)) {
      errors.push(`files["${rawName}"]: expected an object with "rules"`);
      continue;
    }
    const format = spec.format ?? defaultFormatFor(file);
    if (!FORMATS.has(format)) {
      errors.push(
        `files["${rawName}"]: unknown format "${format}" (use json, jsonc or text)`,
      );
      continue;
    }
    const arrays = spec.arrays ?? 'replace';
    if (!ARRAY_POLICIES.has(arrays)) {
      errors.push(
        `files["${rawName}"]: unknown arrays policy "${arrays}" (use replace, concat or unique)`,
      );
      continue;
    }
    if (!isPlainObject(spec.rules) || Object.keys(spec.rules).length === 0) {
      errors.push(`files["${rawName}"]: "rules" must be a non-empty object`);
      continue;
    }
    const banner = resolveBanner(file, format, spec.banner, errors);
    const compiledRules = compileRules(file, format, spec.rules, errors);
    files[file] = { file, format, arrays, banner, ...compiledRules };
  }

  if (errors.length > 0) {
    throw new StencilError(`${label}:\n  - ${errors.join('\n  - ')}`);
  }

  return {
    workspaces: Array.isArray(input.workspaces) ? input.workspaces : null,
    exclude: Array.isArray(input.exclude) ? input.exclude : [],
    files,
  };
}

/** Locate and load stencil.json from the repo root. */
export async function loadConfig(
  root: string,
  explicitPath?: string,
): Promise<{ config: StencilConfig; path: string }> {
  const candidates = explicitPath
    ? [explicitPath]
    : DEFAULT_CONFIG_FILENAMES.map((name) => `${root}/${name}`);
  for (const candidate of candidates) {
    let text: string;
    try {
      text = await readFile(candidate, 'utf8');
    } catch {
      continue;
    }
    const parsed = parseJsonc(text, candidate) as unknown;
    const config = compileConfig(parsed as StencilConfigInput, candidate);
    return { config, path: candidate };
  }
  throw new StencilError(
    `no stencil configuration found (looked for: ${candidates.join(', ')}) — run 'stencil init' first`,
  );
}
